// ECE 366 Project 1 - Problem 2(a)
// 32-bit Carry Lookahead Adder using 4-bit blocks.
// This module is designed to be pasted AFTER the Problem 1 modules.
// It reuses the Problem 1 module named four_bit_RCA.

// One 4-bit CLA block.
// The SUM comes from the Problem 1 4-bit RCA.
// The carry to the next 4-bit block is generated separately from P and G,
// matching the Lecture 2 CLA structure.
module cla_4bit_block(A, B, Cin, S, Cout);
    input  [3:0] A, B;
    input        Cin;
    output [3:0] S;
    output       Cout;

    wire p0, p1, p2, p3;
    wire g0, g1, g2, g3;
    wire p01, p23;
    wire p32, p321;
    wire t1, t2, t3;
    wire g_or1, g_or2;
    wire Pblock, Gblock;
    wire p_cin;
    wire unused_rca_cout;

    // Bit-level propagate: Pi = Ai OR Bi
    or (p0, A[0], B[0]);
    or (p1, A[1], B[1]);
    or (p2, A[2], B[2]);
    or (p3, A[3], B[3]);

    // Bit-level generate: Gi = Ai AND Bi
    and (g0, A[0], B[0]);
    and (g1, A[1], B[1]);
    and (g2, A[2], B[2]);
    and (g3, A[3], B[3]);

    // Block propagate: P3:0 = p3 p2 p1 p0
    and (p01, p0, p1);
    and (p23, p2, p3);
    and (Pblock, p01, p23);

    // Block generate:
    // G3:0 = g3 + p3g2 + p3p2g1 + p3p2p1g0
    and (t1, p3, g2);

    and (p32, p3, p2);
    and (t2, p32, g1);

    and (p321, p32, p1);
    and (t3, p321, g0);

    or (g_or1, g3, t1);
    or (g_or2, g_or1, t2);
    or (Gblock, g_or2, t3);

    // Carry out of the 4-bit CLA block:
    // Cout = G3:0 + P3:0 * Cin
    and (p_cin, Pblock, Cin);
    or  (Cout, Gblock, p_cin);

    // Lecture 2: sum bits are generated by the 4-bit RCA.
    // The RCA's own Cout is intentionally NOT used to feed the next block.
    four_bit_RCA RCA(
        .A(A),
        .B(B),
        .Cin(Cin),
        .S(S),
        .Cout(unused_rca_cout)
    );
endmodule


// Required Problem 2 top-level module.
module CLA(A, B, Cin, S, Cout);
    input  [31:0] A, B;
    input         Cin;
    output [31:0] S;
    output        Cout;

    // block_carry[0] = c0 (top-level Cin)
    // block_carry[1] = c4
    // block_carry[2] = c8
    // ...
    // block_carry[8] = c32 (top-level Cout)
    wire [8:0] block_carry;

    assign block_carry[0] = Cin;

    cla_4bit_block B0(
        .A(A[3:0]), .B(B[3:0]),
        .Cin(block_carry[0]), .S(S[3:0]), .Cout(block_carry[1])
    );

    cla_4bit_block B1(
        .A(A[7:4]), .B(B[7:4]),
        .Cin(block_carry[1]), .S(S[7:4]), .Cout(block_carry[2])
    );

    cla_4bit_block B2(
        .A(A[11:8]), .B(B[11:8]),
        .Cin(block_carry[2]), .S(S[11:8]), .Cout(block_carry[3])
    );

    cla_4bit_block B3(
        .A(A[15:12]), .B(B[15:12]),
        .Cin(block_carry[3]), .S(S[15:12]), .Cout(block_carry[4])
    );

    cla_4bit_block B4(
        .A(A[19:16]), .B(B[19:16]),
        .Cin(block_carry[4]), .S(S[19:16]), .Cout(block_carry[5])
    );

    cla_4bit_block B5(
        .A(A[23:20]), .B(B[23:20]),
        .Cin(block_carry[5]), .S(S[23:20]), .Cout(block_carry[6])
    );

    cla_4bit_block B6(
        .A(A[27:24]), .B(B[27:24]),
        .Cin(block_carry[6]), .S(S[27:24]), .Cout(block_carry[7])
    );

    cla_4bit_block B7(
        .A(A[31:28]), .B(B[31:28]),
        .Cin(block_carry[7]), .S(S[31:28]), .Cout(block_carry[8])
    );

    assign Cout = block_carry[8];
endmodule
